-- ============================================================================
-- TBS / Katta Castrum vendor ware restoration   (manifest v163)
--
-- Six Katta Castrum vendors shipped with an npc_types row (name, merchant
-- class, and -- for some -- an alternate currency) but no merchantlist
-- inventory, so opening them produced an empty window:
--     416039 Master_Pokk         416041 Trader_Hyalunes
--     416047 Trader_Vallarines   416057 Trader_Markus
--     416064 Master_Gulliastus   416076 Trader_Varrina
--
-- This migration fills merchant_id / alt_currency_id on those six and inserts
-- their live inventories.  The price of every row is the per-item
-- alt_currency_cost (Orum 79911 / Phosphene 79912 / Phosphite 79913).
--
-- Source: Buried Sea-era Katta Castrum merchant windows (Latan's merchant
-- guide, angelfire, via the Wayback Machine).  Every existing Katta row in
-- PEQ encodes the per-item faction gate as the sentinel faction_required =
-- -1100 ("no gate"), so the live indiff/amiable/kindly/warmly/ally tiers are
-- not reproduced -- mirroring the other 17 Katta vendors.
--
-- NOTE: Varrina's "Citizen's Energeiac Chain Coat" is priced 350 in the live
-- window, whereas the plate/leather/silk Citizen chest pieces sold by
-- Avatticus/Bartus/Dammides are 300.  The live value is kept here.
--
-- Standalone twin of the manifest entry '20261017_tbs_katta_merchants' (v163).
-- ============================================================================

SET NAMES utf8mb4;

-- ---------------------------------------------------------------------------
-- 1. npc_types: own merchantlist + currency
--    (416039 already had Phosphite 13, 416047 already Orum 11 -- keep those.)
-- ---------------------------------------------------------------------------
UPDATE `npc_types` SET `merchant_id` = `id`
  WHERE `id` IN (416039,416041,416047,416057,416064,416076);

UPDATE `npc_types` SET `alt_currency_id` = 11 WHERE `id` IN (416041,416057,416076);
UPDATE `npc_types` SET `alt_currency_id` = 12 WHERE `id` = 416064;

